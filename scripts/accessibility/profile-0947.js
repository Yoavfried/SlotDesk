async page=>{
  page.setDefaultTimeout(12000);
  const checks=[],scans=[];
  const check=(value,name)=>{if(!value)throw Error(name);checks.push(name);};
  async function scan(name){
    if(!await page.evaluate(()=>!!window.axe))await page.addScriptTag({url:'http://127.0.0.1:8893/__axe.js'});
    const result=await page.evaluate(()=>axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa','best-practice']}}));
    scans.push({name,violations:result.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,message:n.failureSummary}))})),incomplete:result.incomplete.map(v=>({id:v.id,count:v.nodes.length}))});
  }
  const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('slotdesk-settings-v2:google:'+encodeURIComponent('nina@example.test'))).profiles.find(p=>p.email==='nina@example.test'));
  await page.goto('http://127.0.0.1:8893/?case=ready');
  if(await page.locator('#connect').isVisible())await page.locator('#connect').click();
  await page.setViewportSize({width:514,height:900});
  await page.locator('#home-profiles').click();
  await page.locator('[data-profile-choice]').first().click();
  await page.locator('#profile-advanced > summary').click();
  const titles=await page.locator('#profile-advanced > .profile-category > details > summary > span:first-child').allTextContents();
  check(JSON.stringify(titles)===JSON.stringify(['Working days and hours','Convenience hours','Blockers','Notices and buffers','Event detection','Manage meetings']),'Approved section order and helper icons');
  check(await page.locator('#p-clue,#zone-suggestions,#exclusion-list,#add-availability').count()===0,'Removed redundant clues, leave exceptions and new positive-rule controls');
  await page.locator('#profile-blockers + .category-help .category-info').click();
  check(!await page.locator('#profile-blockers').evaluate(el=>el.open),'Help icon does not expand its category');
  check(await page.locator('#profile-blockers-help').isVisible(),'Help text is available on tap');
  await page.locator('#profile-blockers + .category-help .category-info').press('Escape');
  await page.locator('#profile-blockers > summary').click();
  while(await page.locator('[data-remove-blocker]').count()){await page.locator('[data-remove-blocker]').first().click();await page.waitForTimeout(100);}
  await page.locator('#add-profile-blocker').click();
  check(!await page.locator('[data-close=editor]').isVisible(),'Blocker form requires Save or Discard');
  await page.keyboard.press('Escape');
  check(await page.locator('#profile-blocker-form').isVisible(),'Escape retains unsaved blocker entries');
  await page.locator('#pb-label').fill('Private appointment');
  await page.locator('#pb-start').fill('garbage');
  await page.locator('#pb-save').click();
  check((await page.locator('#pb-error').textContent()).includes('valid'),'Invalid blocker times are rejected without silent defaults');
  check(((await saved()).blockers||[]).length===0,'Invalid form creates no saved blocker');
  await page.locator('#pb-start').fill('09:00');
  await scan('blocker-form-light');
  await page.locator('#pb-save').click();
  await page.locator('#profile-blocker-form').waitFor({state:'hidden'});
  check((await saved()).blockers[0].label==='Private appointment','One-off blocker saves to the profile');
  await page.locator('[data-edit-blocker]').click();
  await page.locator('#pb-label').fill('Revised blocker');
  await page.locator('#pb-save').click();
  await page.locator('#profile-blocker-form').waitFor({state:'hidden'});
  check((await saved()).blockers.length===1&&(await saved()).blockers[0].label==='Revised blocker','Editing replaces the chosen blocker');
  await page.locator('[data-remove-blocker]').click();
  await page.waitForFunction(()=>!document.querySelector('[data-remove-blocker]'));
  check((await saved()).blockers.length===0,'X removes a blocker immediately');
  await page.locator('#add-profile-blocker').click();
  await page.locator('#pb-type').selectOption('recurring');
  await page.locator('#pb-label').fill('Weekly overnight block');
  await page.locator('#pb-start').fill('23:00');
  await page.locator('#pb-end').fill('01:00');
  await page.locator('#pb-save').click();
  await page.locator('#profile-blocker-form').waitFor({state:'hidden'});
  check((await page.locator('#profile-blockers-list').textContent()).includes('next day'),'Overnight recurrence is clearly identified');
  const before=JSON.stringify((await saved()).blockers);
  await page.locator('#add-profile-blocker').click();
  await page.locator('#pb-label').fill('Discard this');
  await page.locator('#pb-discard').click();
  check(JSON.stringify((await saved()).blockers)===before,'Discard leaves saved blockers unchanged');
  await page.locator('#profile-detection > summary').click();
  await page.locator('#p-detection').uncheck();
  check(!await page.locator('#p-detection').isChecked(),'Detection can be switched off');
  check(!await page.locator('#profile-detection-fields').isVisible(),'Off hides detection fields');
  await page.locator('#p-detection').check();
  await page.locator('#keyword-input-soft').fill('client hold');
  await page.locator('#keyword-input-soft').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#keyword-soft').textContent.includes('client hold'));
  await page.locator('#keyword-input-soft').blur();
  await page.waitForTimeout(400);
  check((await saved()).keywordCategories.includes('soft'),'Edited category uses whole-word keyword matching');
  check((await saved()).ruleTerms.soft.includes('client hold'),'Keyword additions save live');
  await scan('event-detection-light');
  await page.getByRole('button',{name:'Remove client hold',exact:true}).click();
  await page.waitForTimeout(200);
  check(!(await saved()).ruleTerms.soft.includes('client hold'),'Keyword X saves removal');
  await page.locator('#p-detection').uncheck();
  check(!await page.locator('#profile-detection-fields').isVisible(),'Turning off hides fields and preserves terms');
  await page.locator('#profile-convenience > summary').click();
  await page.locator('#p-ignore-convenience').check();
  check(await page.locator('#p-ok-start').isDisabled(),'Ignored convenience fields are disabled');
  await page.locator('#p-ignore-convenience').uncheck();
  check(await page.locator('#p-ok-start').inputValue()==='07:00','Convenience values survive ignoring');
  await page.locator('#profile-manage-meetings > summary').click();
  await page.locator('#profile-meetings-to').fill('2026-10-29');
  await page.locator('#event-list .meeting-entry').first().waitFor();
  await page.waitForFunction(()=>document.querySelector('#event-list').textContent.includes('next occurrence'));
  check(await page.locator('#profile-meetings-calendars input').count()===1,'Only linked selected calendars are offered');
  const first=page.locator('#event-list .meeting-entry').filter({has:page.getByRole('heading',{name:'Weekly catch-up',exact:true})});
  const next=page.locator('#event-list .meeting-entry').filter({has:page.getByRole('heading',{name:'Weekly catch-up · next occurrence',exact:true})});
  check(await first.locator('[data-profile-scope]').inputValue()==='occurrence','Recurring scope defaults to this occurrence');
  await first.getByRole('button',{name:'Protect',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-profile-treatment="2|protected"]')?.getAttribute('aria-pressed')==='true'||[...document.querySelectorAll('#event-list .meeting-entry')].some(el=>el.querySelector('h3')?.textContent==='Weekly catch-up'&&el.querySelector('[aria-pressed=true]')?.textContent==='Protect'));
  check((await saved()).eventTreatments.at(-1).scope==='occurrence','Treatment saves without an extra confirmation');
  await first.locator('[data-profile-scope]').selectOption('series');
  await first.getByRole('button',{name:'Ignore',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('#event-list .meeting-entry')].filter(el=>el.querySelector('h3')?.textContent.startsWith('Weekly catch-up')).every(el=>el.querySelector('[aria-pressed=true]')?.textContent==='Ignore'));
  check(await next.getByRole('button',{name:'Ignore',exact:true}).getAttribute('aria-pressed')==='true','Entire series replaces earlier occurrence treatment');
  await first.locator('[data-profile-scope]').selectOption('series');
  await first.getByRole('button',{name:'Assign leave',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#event-list').querySelectorAll('[aria-pressed=true]').length>0);
  await page.waitForTimeout(250);
  check(await next.getByRole('button',{name:'Assign leave',exact:true}).getAttribute('aria-pressed')==='true','Assign leave supports entire series');
  await first.getByRole('button',{name:'Default',exact:true}).click();
  await page.waitForTimeout(250);
  check(await first.getByRole('button',{name:'Default',exact:true}).getAttribute('aria-pressed')==='true'&&await next.getByRole('button',{name:'Assign leave',exact:true}).getAttribute('aria-pressed')==='true','Later occurrence Default overrides series only for that occurrence');
  await first.getByRole('button',{name:'View details',exact:true}).click();
  check(await page.locator('#meeting-detail-dialog').isVisible(),'Shared meeting details opens above the profile');
  await page.locator('[data-close=meeting-detail-dialog]').click();
  check(await page.locator('#editor').isVisible(),'Closing details returns to profile');
  await page.locator('#p-allow-overlap').check();
  await page.waitForTimeout(250);
  check((await saved()).allowOverlap,'General overlap preference lives in Manage meetings');
  const reads=await page.evaluate(()=>fetch('/__stats').then(r=>r.json()).then(s=>s.sourceReads.length));
  await page.locator('#profile-manage-meetings .meeting-calendar-picker > summary').click();
  await page.locator('#profile-calendars-clear').click();
  await page.locator('#profile-calendars-all').click();
  check(await page.evaluate(()=>fetch('/__stats').then(r=>r.json()).then(s=>s.sourceReads.length))===reads,'Calendar filter changes use cached events');
  for(const width of [320,514,1280]){
    await page.setViewportSize({width,height:900});
    check(!await page.locator('#editor').evaluate(el=>el.scrollWidth>el.clientWidth),'Profile popup has no horizontal overflow at '+width);
    check(!await page.locator('#event-list').evaluate(el=>el.scrollWidth>el.clientWidth),'Meeting controls fit at '+width);
  }
  await scan('profile-meetings-light');
  await page.locator('[data-close=editor]').click();
  await page.locator('[data-profile-choice]').first().click();
  await page.locator('#profile-advanced > summary').click();
  check((await saved()).blockers.length===1,'Blockers survive closing and reopening');
  await scan('profile-reopened-light');
  await page.locator('[data-close=editor]').click();
  await page.locator('#create-profile').click();
  await page.locator('#profile-advanced > summary').click();
  check(!await page.locator('#p-detection').isChecked(),'New profiles start with event detection off');
  check(!await page.locator('#profile-detection-fields').isVisible(),'New-profile detection fields stay hidden');
  await page.locator('[data-close=editor]').click();
  const stats=await page.evaluate(()=>fetch('/__stats').then(r=>r.json()));
  check(stats.posts===0&&stats.patches.length===0&&stats.altered.length===0&&stats.unsafeMethods===0,'Profile changes never write to or change calendar appointments');
  if(scans.some(s=>s.violations.length))throw Error(JSON.stringify(scans.filter(s=>s.violations.length)));
  return {checks,scans,stats:{posts:stats.posts,patches:stats.patches.length,altered:stats.altered.length,unsafeMethods:stats.unsafeMethods}};
}

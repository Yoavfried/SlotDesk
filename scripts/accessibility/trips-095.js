async page=>{
  page.setDefaultTimeout(12000);
  const checks=[],scans=[],errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const check=(value,name)=>{if(!value)throw Error(name);checks.push(name);};
  const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('slotdesk-settings-v2:google:'+encodeURIComponent('nina@example.test'))));
  const own=async()=>{const s=await stored();return s.profiles.find(p=>p.id===s.settings.ownProfileId);};
  async function scan(name){
    if(!await page.evaluate(()=>!!window.axe))await page.addScriptTag({url:'http://127.0.0.1:8893/__axe.js'});
    const result=await page.evaluate(()=>axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa','best-practice']}}));
    scans.push({name,violations:result.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,message:n.failureSummary}))}))});
  }
  await page.goto('http://127.0.0.1:8893/?case=ready');
  await page.evaluate(()=>localStorage.removeItem('slotdesk-v091-fixture:ready'));
  await page.reload();
  if(await page.locator('#connect').isVisible())await page.locator('#connect').click();
  await page.setViewportSize({width:514,height:900});
  await page.locator('#home-profiles').click();
  await page.locator('[data-profile-travel]').first().click();
  check(await page.locator('#trips-dialog').isVisible(),'Trips opens independently from Edit profile');
  check(!await page.locator('#editor').isVisible(),'Trip manager does not open profile settings');
  await page.locator('#trip-add').click();
  check(!await page.locator('.trip-flight-details').isVisible(),'New flight starts with departure date only');
  await page.keyboard.press('Escape');
  check(await page.locator('#trip-editor').isVisible(),'Only Save or Discard exits the trip editor');
  await page.locator('#trip-name').fill('London and New York');
  await page.locator('[data-field=departureDate]').fill('2027-01-10');
  await page.locator('[data-field=departureDate]').blur();
  await page.locator('.trip-flight-details').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('[data-match-note]').textContent.includes('Looking'));
  check((await page.locator('[data-match-note]').textContent()).includes('No matching flight'),'Missing calendar flight opens manual entry');
  async function place(index,side,query,code){
    const box=page.locator('[data-leg="'+index+'"]');
    await box.locator('[data-place='+side+']').fill(query);
    await box.locator('[data-place-results='+side+'] button').filter({hasText:code}).first().click();
  }
  await place(0,'departure','TLV','TLV');
  await place(0,'arrival','Heathrow','LHR');
  await page.locator('[data-field=departureTime]').fill('10:00');
  await page.locator('[data-field=departureTime]').blur();
  check((await page.locator('[data-estimate-note]').textContent()).includes('Estimated arrival'),'Route and time give an editable local arrival estimate');
  check(!!await page.locator('[data-field=arrivalDate]').inputValue(),'Estimate supplies arrival date');
  await scan('trip-editor-light');
  await page.locator('#trip-save').click();
  await page.locator('#trip-editor').waitFor({state:'hidden'});
  check((await own()).trips.length===1,'Save persists one complete trip');
  const before=JSON.stringify((await own()).trips);
  await page.locator('[data-trip-edit]').click();
  await page.locator('#trip-name').fill('Discard this change');
  await page.locator('#trip-discard').click();
  check(JSON.stringify((await own()).trips)===before,'Discard preserves the saved trip');
  await page.locator('[data-trip-edit]').click();
  await page.locator('#trip-next').click();
  await page.locator('[data-leg="1"] [data-field=departureDate]').fill('2027-01-10');
  await page.locator('[data-leg="1"] [data-field=departureDate]').blur();
  await page.locator('[data-leg="1"] .trip-flight-details').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('[data-leg="1"] [data-match-note]').textContent.includes('Looking'));
  await place(1,'arrival','JFK','JFK');
  await page.locator('[data-leg="1"] [data-field=departureTime]').fill('18:00');
  await page.locator('[data-leg="1"] [data-field=departureTime]').blur();
  await page.locator('[data-leg="1"] [data-field=connection]').check();
  await page.locator('#trip-back').click();
  check((await page.locator('[data-leg="2"] [data-place=arrival]').inputValue()).includes('TLV'),'Flight back prefills the trip origin');
  await page.locator('[data-leg="2"] [data-field=departureDate]').fill('2027-01-15');
  await page.locator('[data-leg="2"] [data-field=departureDate]').blur();
  await page.locator('[data-leg="2"] .trip-flight-details').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('[data-leg="2"] [data-match-note]').textContent.includes('Looking'));
  await page.locator('[data-leg="2"] [data-field=departureTime]').fill('20:00');
  await page.locator('[data-leg="2"] [data-field=departureTime]').blur();
  check(!await page.locator('#trip-open-ended').isVisible(),'Return trip has no open-ended timezone warning');
  await page.locator('#trip-save').click();
  await page.locator('#trip-editor').waitFor({state:'hidden'});
  check((await own()).trips[0].flights.length===3,'Connection and return save as one ordered trip');
  await page.setViewportSize({width:280,height:740});
  await page.locator('[data-trip-edit]').click();
  check(await page.locator('#trip-editor').evaluate(el=>el.scrollWidth<=el.clientWidth),'Narrow trip dialog has no horizontal overflow');
  const height=await page.locator('#trip-editor').evaluate(el=>el.getBoundingClientRect().height);
  await page.locator('[data-place=departure]').first().fill('London');
  check(Math.abs(height-await page.locator('#trip-editor').evaluate(el=>el.getBoundingClientRect().height))<1,'Airport suggestions do not resize the popup');
  await page.locator('#trip-name').click();
  check(await page.locator('[data-place-results]:visible').count()===0,'Clicking away closes place suggestions');
  await scan('trip-editor-narrow');
  await page.locator('#trip-discard').click();
  await page.locator('#trips-close').click();
  await page.setViewportSize({width:514,height:900});
  await page.locator('[data-profile-choice]').first().click();
  check(!await page.locator('#profile-travel').isVisible(),'Trip settings removed from advanced profile sections');
  await page.locator('[data-close=editor]').click();
  await page.locator('#profiles-workspace .back-home').click();
  await page.locator('#home-new-meeting').click();
  check(await page.locator('[data-trip]').count()>0,'New meeting includes the flight action');
  const initial=await page.locator('[data-person-now]').first().textContent();
  const card=await page.locator('[data-person-now]').first().evaluate(el=>{window.clockCard=el.closest('article')||el.parentElement;return true;});
  await page.evaluate(()=>{const Original=Date,offset=2*60000;window.Date=class extends Original{constructor(...args){super(...(args.length?args:[Original.now()+offset]));}static now(){return Original.now()+offset;}};window.dispatchEvent(new Event('focus'));});
  check(initial!==await page.locator('[data-person-now]').first().textContent(),'Participant clock catches up without a screen refresh');
  check(await page.locator('[data-person-now]').first().evaluate(el=>window.clockCard.contains(el)),'Clock updates preserve the original card');
  await page.locator('[data-trip]').first().click();
  await page.evaluate(()=>window.confirm=()=>true);
  await page.locator('[data-trip-delete]').click();
  await page.waitForFunction(()=>!document.querySelector('[data-trip-delete]'));
  check((await own()).trips.length===0,'Deleting a trip removes local trip data');
  await page.locator('#trips-close').click();
  const stats=await page.evaluate(()=>fetch('/__stats').then(r=>r.json()));
  check(stats.posts===0&&stats.patches.length===0&&stats.unsafeMethods===0&&stats.unchanged===9,'Trip and profile actions make no calendar writes; all 9 baseline events unchanged');
  check(errors.length===0,'No browser runtime errors');
  if(scans.some(s=>s.violations.length))throw Error(JSON.stringify(scans.filter(s=>s.violations.length)));
  return {checks,scans,errors,stats:{posts:stats.posts,patches:stats.patches,unchanged:stats.unchanged}};
}

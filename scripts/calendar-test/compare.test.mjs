import assert from 'node:assert/strict';
import { compare, inventory } from './compare-calendars.mjs';
let checks = 0;
const eq = (a, b) => { assert.deepEqual(a, b); checks++; };
const throws = (fn) => { assert.throws(fn); checks++; };
const event = (id = 'a', extra = '') => `BEGIN:VEVENT\nUID:${id}\nDTSTAMP:20261012T000000Z\nSUMMARY:Test\nDTSTART:20261020T100000Z\nDTEND:20261020T110000Z\n${extra}END:VEVENT\n`;
const calendar = body => `BEGIN:VCALENDAR\nVERSION:2.0\nX-WR-TIMEZONE:UTC\n${body}END:VCALENDAR\n`;
const baseline = calendar(event('a') + event('b'));
eq(compare(baseline, baseline).passed, true);
eq(compare(baseline, calendar(event('a'))).removedCount, 1);
eq(compare(baseline, baseline.replace('SUMMARY:Test', 'SUMMARY:Changed')).changedCount, 1);
eq(compare(baseline, baseline.replace('DTSTART:20261020T100000Z', 'DTSTART:20261020T101500Z')).passed, false);
eq(compare(baseline, calendar(event('a') + event('b') + event('c')), 1).passed, true);
eq(compare(baseline, calendar(event('a') + event('c')), 1).passed, false);
eq(compare(baseline, calendar(event('a') + event('b') + event('c')), 0).passed, false);
eq(compare(baseline, baseline.replaceAll('20261012T000000Z', '20261013T000000Z')).passed, true);
eq(compare(baseline, baseline.replace('X-WR-TIMEZONE:UTC', 'X-WR-TIMEZONE:Asia/Jerusalem')).timezoneChanged, true);
eq(compare(calendar(event('r', 'RRULE:FREQ=DAILY;COUNT=2\n')), calendar(event('r', 'RRULE:FREQ=DAILY;COUNT=3\n'))).changedCount, 1);
eq(compare(calendar(event('r')), calendar(event('r', 'ATTENDEE:mailto:guest@example.test\n'))).changedCount, 1);
eq(compare(calendar(event('r', 'LOCATION:Room\n')), calendar(event('r', 'LOCATION:Elsewhere\n'))).changedCount, 1);
eq(compare(calendar(event('r', 'BEGIN:VALARM\nACTION:DISPLAY\nTRIGGER:-PT5M\nEND:VALARM\n')), calendar(event('r', 'BEGIN:VALARM\nACTION:DISPLAY\nTRIGGER:-PT10M\nEND:VALARM\n'))).changedCount, 1);
eq(compare(calendar(event('r', 'DESCRIPTION:Folded content\n')), calendar(event('r', 'DESCRIPTION:Folded\n content\n'))).passed, false);
eq(compare(calendar(event('r', 'DESCRIPTION:Foldedcontent\n')), calendar(event('r', 'DESCRIPTION:Folded\n content\n'))).passed, true);
eq(inventory(calendar(event('r') + event('r', 'RECURRENCE-ID:20261027T100000Z\n'))).events.size, 2);
throws(() => inventory(calendar(event('a') + event('a'))));
throws(() => inventory(baseline.replace('END:VCALENDAR', '')));
throws(() => inventory(calendar('')));
throws(() => compare(baseline, baseline, -1));
eq(compare(baseline, baseline.replace(/\n/g, '\r\n')).passed, true);
eq(compare(baseline, baseline.replace('SUMMARY:Test\nDTSTART', 'DTSTART').replace('DTEND:20261020T110000Z', 'DTEND:20261020T110000Z\nSUMMARY:Test')).passed, true);
console.log(checks + ' local calendar-comparison checks passed; no network or calendar changes.');
